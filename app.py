@app.post('/requests/<int:rid>/accept')

@role_required('donor','admin')

def accept_request(rid):

    con=db(); u=current_user(); req=con.execute('SELECT * FROM requests WHERE id=%s',(rid,)).fetchone()

    if not req: abort(404)

    if u['role']=='donor':

        if not (u['available'] and u['alert_consent'] and u['blood_group'] in COMPATIBLE[req['blood_group']] and u['city'].lower()==req['city'].lower()): abort(403)

        allowed=con.execute('SELECT 1 FROM notifications WHERE user_id=%s AND request_id=%s',(u['id'],rid)).fetchone()

        if not allowed: abort(403)

    cur=con.execute("UPDATE requests SET status='accepted',accepted_by=%s,updated_at=%s WHERE id=%s AND status='pending'",(u['id'],now(),rid)); con.commit()

    flash('You accepted the request.' if cur.rowcount else 'This request is no longer pending.', 'success' if cur.rowcount else 'error'); return redirect(url_for('dashboard') if u['role']!='admin' else url_for('admin'))



