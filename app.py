def login_required(fn):

    @wraps(fn)

    def wrapped(*a, **kw):

        if not current_user(): flash('Please sign in to continue.', 'error'); return redirect(url_for('login'))

        return fn(*a, **kw)

    return wrapped



def role_required(*roles):

    def deco(fn):

        @wraps(fn)

        def wrapped(*a, **kw):

            u = current_user()

            if not u: return redirect(url_for('login'))

            if u['role'] not in roles: abort(403)

            return fn(*a, **kw)

        return wrapped

    return deco



def valid_email(value): return bool(re.fullmatch(r'^[^\s@]+@[^\s@]+\.[^\s@]+$', value or ''))

def clean(value, maxlen=120): return (value or '').strip()[:maxlen]



def city_options():

    stored = [r['city'] for r in db().execute(
        "SELECT city FROM ("
        "SELECT DISTINCT city FROM users WHERE city IS NOT NULL AND trim(city)<>'' "
        "UNION "
        "SELECT DISTINCT city FROM requests WHERE city IS NOT NULL AND trim(city)<>''"
        ") AS all_cities ORDER BY LOWER(city)"
    )]

    return sorted(set(KARNATAKA_CITIES + stored), key=str.casefold)



