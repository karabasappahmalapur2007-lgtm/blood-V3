@app.route('/dashboard', methods=['GET','POST'])

@login_required

def dashboard():

    u=current_user(); con=db()

    if u['role']=='admin': return redirect(url_for('admin'))

    if request.method=='POST' and u['role']=='donor' and request.form.get('action')=='profile':

        group=request.form.get('blood_group',''); city=clean(request.form.get('city'),100); phone=clean(request.form.get('phone'),25)

        if group not in GROUPS or len(city)<2 or len(phone)<7: flash('Please provide a valid blood group, city and phone number.', 'error')

        else:

            con.execute('UPDATE users SET blood_group=%s,city=%s,phone=%s,available=%s,alert_consent=%s WHERE id=%s',

                        (group,city,phone,1 if request.form.get('available')=='on' else 0,1 if request.form.get('alert_consent')=='on' else 0,u['id'])); con.commit(); flash('Donor profile updated.', 'success')

        return redirect(url_for('dashboard'))

    if request.method=='POST' and u['role'] in ('patient','doctor','hospital') and request.form.get('action')=='request':

        group=request.form.get('blood_group',''); city=clean(request.form.get('city'),100); hospital=clean(request.form.get('hospital'),140); details=clean(request.form.get('details'),500)

        try: units=int(request.form.get('units','1'))

        except (TypeError, ValueError): units=0

        priority=request.form.get('priority','urgent')

        if group not in GROUPS or len(city)<2 or len(hospital)<2 or not 1 <= units <= 20 or priority not in ('critical','urgent','routine'): flash('Enter a valid blood group, city and hospital.', 'error')

        else:

            cur=con.execute('INSERT INTO requests(patient_id,patient_name,blood_group,city,hospital,details,units,priority,created_at,updated_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id',

                            (u['id'],u['name'],group,city,hospital,details,units,priority,now(),now()))

            rid=cur.fetchone()['id']

            placeholders=','.join(['%s'] * len(COMPATIBLE[group]))

            matches=con.execute("SELECT id FROM users WHERE role='donor' AND available=1 AND alert_consent=1 AND blood_group IN (" + placeholders + ") AND lower(city)=lower(%s)", (*COMPATIBLE[group],city)).fetchall()

            for donor in matches:

                con.execute('INSERT INTO notifications(user_id,request_id,message,created_at) VALUES(%s,%s,%s,%s) ON CONFLICT(user_id,request_id) DO NOTHING', (donor['id'],rid,f"{priority.title()} request: {units} unit(s) of {group} blood needed in {city} at {hospital}.",now()))

            con.commit(); flash(f'Emergency request #{rid} saved. {len(matches)} opted-in matching donor(s) were notified in LifeLink.', 'success')

        return redirect(url_for('dashboard'))

    if u['role']=='donor':

        notifications=con.execute('SELECT n.*,r.blood_group,r.city,r.hospital,r.status FROM notifications n JOIN requests r ON r.id=n.request_id WHERE n.user_id=%s ORDER BY n.created_at DESC',(u['id'],)).fetchall()

        history=con.execute('SELECT r.*,u.name AS donor_name FROM requests r LEFT JOIN users u ON u.id=r.accepted_by WHERE r.accepted_by=%s ORDER BY r.created_at DESC',(u['id'],)).fetchall()

        return render_template('dashboard.html', user=u, notifications=notifications, history=history, cities=city_options())

    requests=con.execute('SELECT r.*, (SELECT COUNT(*) FROM notifications n WHERE n.request_id=r.id) AS notified FROM requests r WHERE r.patient_id=%s ORDER BY r.created_at DESC',(u['id'],)).fetchall()

    return render_template('dashboard.html', user=u, requests=requests, cities=city_options())



