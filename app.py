SCHEMA = '''

CREATE TABLE IF NOT EXISTS users(

 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

 name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,

 role TEXT NOT NULL CHECK(role IN ('donor','patient','doctor','hospital','admin')),

 phone TEXT, blood_group TEXT, city TEXT, available INTEGER NOT NULL DEFAULT 0,

 alert_consent INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL

);

CREATE TABLE IF NOT EXISTS requests(

 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

 patient_id BIGINT NOT NULL REFERENCES users(id), patient_name TEXT NOT NULL,

 blood_group TEXT NOT NULL, city TEXT NOT NULL, hospital TEXT NOT NULL,

 details TEXT NOT NULL DEFAULT '', units INTEGER NOT NULL DEFAULT 1,

 priority TEXT NOT NULL DEFAULT 'urgent',

 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','completed','cancelled')),

 accepted_by BIGINT REFERENCES users(id), created_at TEXT NOT NULL, updated_at TEXT NOT NULL

);

CREATE TABLE IF NOT EXISTS notifications(

 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

 user_id BIGINT NOT NULL REFERENCES users(id), request_id BIGINT NOT NULL REFERENCES requests(id),

 message TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL,

 UNIQUE(user_id, request_id)

);

CREATE TABLE IF NOT EXISTS rate_limits(bucket TEXT PRIMARY KEY, hits INTEGER NOT NULL, window_start BIGINT NOT NULL);

CREATE INDEX IF NOT EXISTS idx_users_match ON users(role,blood_group,city,available,alert_consent);

CREATE INDEX IF NOT EXISTS idx_requests_status ON requests(status,created_at);

CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id,is_read,created_at);

'''



