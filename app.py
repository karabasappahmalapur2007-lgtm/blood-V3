@app.route('/register', methods=['GET','POST'])

def register():

    if request.method == 'POST':

        name,email,password = clean(request.form.get('name'),80),clean(request.form.get('email'),160).lower(),request.form.get('password','')

        role = request.form.get('role','donor'); phone=clean(request.form.get('phone'),25); group=request.form.get('blood_group',''); city=clean(request.form.get('city'),100)

        if role not in ('donor','patient','doctor','hospital'): flash('Choose a valid account type.', 'error')

        elif len(name)<2 or not valid_email(email) or len(password)<10 or not re.search(r'[A-Za-z]',password) or not re.search(r'\d',password): flash('Enter a name, valid email, and password with at least 10 characters including a letter and a number.', 'error')

        elif role=='donor' and (group not in GROUPS or len(city)<2 or len(phone)<7): flash('Donor accounts require a valid blood group, city and phone number.', 'error')

        else:

            try:

                cur=db().execute('INSERT INTO users(name,email,password_hash,role,phone,blood_group,city,available,alert_consent,created_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id',

                  (name,email,generate_password_hash(password),role,phone if role=='donor' else None,group if role=='donor' else None,city if role=='donor' else '',0,0,now()))

                new_user_id=cur.fetchone()['id']

                db().commit(); session.clear(); session['user_id']=new_user_id; session.permanent=True

                flash('Account created. You are signed in.', 'success'); return redirect(url_for('dashboard'))

            except IntegrityError:
                db().rollback()
                flash('An account with that email already exists.', 'error')

    return render_template('auth.html', mode='register', groups=GROUPS, role_default=request.args.get('role') if request.args.get('role') in ('donor','patient','doctor','hospital') else 'donor', cities=city_options())



@app.route('/login', methods=['GET','POST'])

@app.route('/login/<portal>', methods=['GET','POST'])

def login(portal=None):

    portal_roles = {'donor':'donor', 'patient':'patient', 'doctor-hospital':('doctor','hospital')}

    if portal is not None and portal not in portal_roles: abort(404)

    if request.method=='POST':

        email=clean(request.form.get('email'),160).lower(); user=db().execute('SELECT * FROM users WHERE email=%s',(email,)).fetchone()

        if user and check_password_hash(user['password_hash'],request.form.get('password','')) and (portal is None or user['role'] in ((portal_roles[portal],) if isinstance(portal_roles[portal], str) else portal_roles[portal])):

            session.clear(); session['user_id']=user['id']; session.permanent=True

            return redirect(url_for('admin') if user['role']=='admin' else url_for('dashboard'))

        flash('Email, password, or selected portal is incorrect.', 'error')

    return render_template('auth.html', mode='login', groups=GROUPS, portal=portal)



